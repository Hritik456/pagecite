"""golden.jsonl -> golden_review.md: every row with its source sentence, checked against the PDF.

    uv run python -m eval.make_review

For each expected entry the PDF page is parsed with the pipeline's own parser
(apps/worker/parsing.py, the text the chunks come from) and the quote must occur on that page after
whitespace is collapsed. Any miss fails the run, with the closest span on the page, so every row in
the review is mechanically grounded. Each row also gets its lexical overlap score (eval/overlap.py),
with a flag above 0.6, and the header gives the mean overlap per kind.
"""

import difflib
import re
import sys
from collections import defaultdict
from functools import lru_cache
from pathlib import Path

# apps.api must be imported before apps.worker.parsing (an existing import cycle resolves only in
# that order); .overlap imports apps.api.retrieval, so it comes first.
from .overlap import FLAG_ABOVE, flagged, overlap  # isort: skip
from apps.worker.parsing import PDF, parse_document  # isort: skip

from .build_corpus import PDF_DIR, load_manifest
from .golden import KINDS, GoldenRow, load_golden

REVIEW = Path(__file__).resolve().parent / "golden_review.md"
_CIRCULAR = re.compile(r"RBI/(?:[A-Z]+/)?\d{4}-\d{2,4}/\d+|FEMA \d+\(R\)/(?:\(\d\)/)?\d{4}-RB")


def norm(text: str) -> str:
    return " ".join(text.split())


def _no_ocr(image, timeout_s):
    raise RuntimeError("the corpus has no scanned pages; OCR is not expected here")


@lru_cache(maxsize=None)
def pages_of(document: str) -> dict[int, str]:
    data = (PDF_DIR / document).read_bytes()
    return {p.page_no: norm(p.text) for p in parse_document(data, PDF, _no_ocr)}


@lru_cache(maxsize=None)
def circular_no(document: str) -> str:
    m = _CIRCULAR.search(pages_of(document).get(1, ""))
    return m.group(0) if m else "?"


def closest(page_text: str, quote: str) -> str:
    sm = difflib.SequenceMatcher(None, page_text, quote, autojunk=False)
    m = sm.find_longest_match(0, len(page_text), 0, len(quote))
    start = max(0, m.a - 40)
    return page_text[start:m.a + len(quote) + 40]


def check_quotes(rows: list[GoldenRow], corpus_files: set[str]) -> list[str]:
    problems = []
    for row in rows:
        for e in row.expected:
            if e.document not in corpus_files:
                problems.append(f"{row.id}: {e.document} is not in eval/corpus.json")
                continue
            page = pages_of(e.document).get(e.page)
            if page is None:
                problems.append(f"{row.id}: {e.document} has no page {e.page}")
            elif norm(e.quote) not in page:
                problems.append(f"{row.id}: quote not on {e.document} p.{e.page}\n    quote:   {norm(e.quote)[:160]}"
                                f"\n    closest: {closest(page, norm(e.quote))[:240]}")
    return problems


def render(rows: list[GoldenRow]) -> str:
    scores = {r.id: overlap(r.question, [e.quote for e in r.expected], r.kind) for r in rows}
    by_kind: dict[str, list[float]] = defaultdict(list)
    for r in rows:
        if scores[r.id] is not None:
            by_kind[r.kind].append(scores[r.id])
    counts = {k: sum(r.kind == k for r in rows) for k in KINDS}
    n_flagged = sum(flagged(s) for s in scores.values())

    out = [
        "# Golden set review",
        "",
        "Generated by `uv run python -m eval.make_review` from `eval/golden.jsonl`. Every quote below was found on the "
        "stated page of the PDF, parsed by the pipeline's own parser.",
        "",
        f"**{len(rows)} rows**: " + ", ".join(f"{k} {counts[k]}" for k in KINDS) + ".",
        "",
        f"**Lexical overlap** is the share of the question's content words (BM25 tokens, stopwords removed) that also "
        f"appear in the quote. For `identifier` and `bank_type` rows the circular number and the bank-type words are "
        f"not scored. ⚠ marks a score above {FLAG_ABOVE}. **Flagged: {n_flagged}.**",
        "",
        "| Kind | Rows | Mean overlap | Max |",
        "|---|---|---|---|",
    ]
    for k in KINDS:
        vals = by_kind.get(k)
        out.append(f"| {k} | {counts[k]} | {sum(vals) / len(vals):.2f} | {max(vals):.2f} |" if vals
                   else f"| {k} | {counts[k]} | n/a | n/a |")
    out += ["", "---", ""]

    for r in rows:
        s = scores[r.id]
        score = "n/a" if s is None else f"{s:.2f}" + (" ⚠" if flagged(s) else "")
        out += [f"### {r.id} · {r.kind} · overlap {score}", "", f"**Q:** {r.question}", "",
                f"**Expected answer:** {r.reference_answer}", ""]
        if not r.expected:
            out += ["**Source:** none (must abstain: \"Not found in the documents.\")", ""]
        for e in r.expected:
            out += [f"**Source:** `{e.document}` ({circular_no(e.document)}), p.{e.page}", "", f"> {norm(e.quote)}", ""]
        out += ["---", ""]
    return "\n".join(out)


def main() -> int:
    rows = load_golden()
    corpus_files = {f["file"] for f in load_manifest()["files"]}
    problems = check_quotes(rows, corpus_files)
    if problems:
        print(f"{len(problems)} problem(s):")
        for p in problems:
            print(f"  {p}")
        return 1
    REVIEW.write_text(render(rows), encoding="utf-8", newline="\n")
    flagged_ids = [r.id for r in rows if flagged(overlap(r.question, [e.quote for e in r.expected], r.kind))]
    print(f"wrote {REVIEW.name}: {len(rows)} rows, every quote found on its page; flagged: {flagged_ids or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
